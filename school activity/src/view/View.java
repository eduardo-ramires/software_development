    private void saveMatriculaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveMatriculaActionPerformed
    AlunoDao dao = new AlunoDao();
    int idAluno = dao.buscarIdAluno(aluno.getSelectedItem().toString());
    
    ProfessorDao dao1 = new ProfessorDao();
    int idProfessor = dao1.buscarIdProfessor(professor.getSelectedItem().toString());
     
    Matricula m = new Matricula();
    m.setAlunoId(idAluno);
    m.setProfessorId(idProfessor);
    m.setData_matricula(new Date(System.currentTimeMillis()));

    MatriculaDao dao2 = new MatriculaDao();
    dao2.insert(m);

    JOptionPane.showMessageDialog(this, "Aluno matriculado com sucesso!");
    }//GEN-LAST:event_saveMatriculaActionPerformed

    private void saveProfessorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveProfessorActionPerformed
        Professor p = new Professor();
        p.setNome(nome.getText());
        p.setIdade(Integer.parseInt(txtIdade.getText().trim()));
        p.setDisciplina(disciplina.getSelectedItem().toString());

        ProfessorDao dao = new ProfessorDao();
        dao.insert(p);

        JOptionPane.showMessageDialog(this, "Professor salvo com sucesso!");
        carregarDados();
        nome.setText("");
        txtIdade.setText("");
    }//GEN-LAST:event_saveProfessorActionPerformed


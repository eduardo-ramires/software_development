    private void carregarDados() {
    aluno.removeAllItems();
    AlunoDao dao = new AlunoDao();
    for (String nome : dao.listarAlunos()) {
        aluno.addItem(nome);
    }
    
    professor.removeAllItems();
    ProfessorDao dao1 = new ProfessorDao();
    for (String nome : dao1.listaProfessores()) {
        professor.addItem(nome);
    }
}


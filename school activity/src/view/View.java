    private void saveAlunoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveAlunoActionPerformed
        Aluno a = new Aluno();
        a.setNome(nome.getText());
        a.setIdade(Integer.parseInt(txtIdade.getText().trim()));
        a.setCurso(curso.getSelectedItem().toString());

        AlunoDao dao = new AlunoDao();
        dao.insert(a);

        JOptionPane.showMessageDialog(this, "Aluno salvo com sucesso!");
        carregarDados();
        nome.setText("");
        txtIdade.setText("");
    }//GEN-LAST:event_saveAlunoActionPerformed

